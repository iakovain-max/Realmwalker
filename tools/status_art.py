def _check(name: str) -> list[str]:
    pat = ART[name]
    if len(pat) != 10 or any(len(row) != 10 for row in pat):
        raise ValueError(f"status icon {name!r} is not 10x10")
    for row in pat:
        for ch in row:
            if ch != "." and ch not in PALETTE:
                raise ValueError(f"status icon {name!r} uses unknown colour {ch!r}")
    return pat


def status_icon(name: str) -> Image.Image:
    """The 10x10 RGBA picture for a status id."""
    pat = _check(name)
    img = Image.new("RGBA", (10, 10), (0, 0, 0, 0))
    for y, row in enumerate(pat):
        for x, ch in enumerate(row):
            if ch != ".":
                img.putpixel((x, y), PALETTE[ch])
    return img


def contact_sheet(path: str, scale: int = 6) -> None:
    """Every icon, scaled up, on dark grey, so a person can look at them."""
    cols = 8
    cell = 10 * scale
    gap = 4
    rows = (len(STATUS_NAMES) + cols - 1) // cols
    w = gap + cols * (cell + gap)
    h = gap + rows * (cell + gap)
    sheet = Image.new("RGBA", (w, h), (40, 38, 36, 255))
    for i, name in enumerate(STATUS_NAMES):
        big = status_icon(name).resize((cell, cell), Image.NEAREST)
        x = gap + (i % cols) * (cell + gap)
        y = gap + (i // cols) * (cell + gap)
        sheet.alpha_composite(big, (x, y))
    sheet.convert("RGB").save(path)


